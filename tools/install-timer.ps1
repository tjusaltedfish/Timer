# Installs the latest Windows build for daily use and puts a "Timer" shortcut
# on the desktop. Re-run after each tools/build-windows.ps1 -Mode release to update.
#
# - Client files: %USERPROFILE%\Apps\Timer\client (replaced on each install;
#   app data stays in %LOCALAPPDATA%\TimePlanner\data and is never touched).
# - Launcher: starts the computer backend (this checkout's server\.venv) on
#   127.0.0.1:8787 if it is not already running, then opens the client.
#   The backend keeps running after the window closes, so WeChat replies and
#   reminders continue.
param([string] $Build, [switch] $LauncherOnly)
$ErrorActionPreference = 'Stop'
$repo = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
if (-not $Build) {
    $record = Join-Path $repo 'artifacts\windows-preview.json'
    if (-not (Test-Path -LiteralPath $record)) { throw 'No Windows build found; run tools/build-windows.ps1 -Mode release first.' }
    $Build = (Get-Content -LiteralPath $record -Raw | ConvertFrom-Json).output
}
if (-not (Test-Path -LiteralPath (Join-Path $Build 'time_planner.exe'))) { throw "Build folder has no time_planner.exe: $Build" }
$python = Join-Path $repo 'server\.venv\Scripts\python.exe'
if (-not (Test-Path -LiteralPath $python)) { throw 'Backend environment missing: server\.venv' }

$home_ = Join-Path $env:USERPROFILE 'Apps\Timer'
$client = Join-Path $home_ 'client'
New-Item -ItemType Directory -Force -Path $home_ | Out-Null
if (-not $LauncherOnly) {
    if (Get-Process -Name time_planner -ErrorAction SilentlyContinue | Where-Object { -not $_.Path -or $_.Path -like "$client*" }) {
        throw 'Timer is open; close it before updating (or use -LauncherOnly).'
    }
    if (Test-Path -LiteralPath $client) { Remove-Item -LiteralPath $client -Recurse -Force }
    & robocopy $Build $client /E /NFL /NDL /NJH /NJS | Out-Null
    if ($LASTEXITCODE -gt 7) { throw 'Could not copy the client files.' }
}

$launcher = Join-Path $home_ 'Start-Timer.ps1'
@"
# Generated by tools/install-timer.ps1; re-run that script instead of editing.
# -BackendOnly starts the backend and tunnel without opening a window (used by tools/release.ps1).
param([switch] `$BackendOnly)
`$ErrorActionPreference = 'Stop'
`$server = '$(Join-Path $repo 'server')'
`$python = '$python'
`$logs = Join-Path `$env:LOCALAPPDATA 'TimePlanner\logs'
function Test-Backend {
    try { (Invoke-WebRequest -UseBasicParsing -TimeoutSec 1 'http://127.0.0.1:8787/health').StatusCode -eq 200 } catch { `$false }
}
if (-not (Test-Backend)) {
    New-Item -ItemType Directory -Force -Path `$logs | Out-Null
    Start-Process -FilePath `$python -WorkingDirectory `$server -WindowStyle Hidden ``
        -ArgumentList '-m','uvicorn','app.main:app','--host','127.0.0.1','--port','8787','--log-level','warning' ``
        -RedirectStandardOutput (Join-Path `$logs 'server.out.log') -RedirectStandardError (Join-Path `$logs 'server.err.log')
    foreach (`$i in 1..30) { if (Test-Backend) { break }; Start-Sleep -Milliseconds 500 }
}
# The tunnel (only the app API and the WeChat callback are public); see docs/guides.
`$cloudflared = Join-Path `$env:USERPROFILE 'Apps\cloudflared\cloudflared.exe'
`$tunnel = Join-Path `$env:USERPROFILE 'Apps\cloudflared\timer.yml'
if ((Test-Path `$tunnel) -and -not (Get-Process -Name cloudflared -ErrorAction SilentlyContinue)) {
    New-Item -ItemType Directory -Force -Path `$logs | Out-Null
    Start-Process -FilePath `$cloudflared -WindowStyle Hidden ``
        -ArgumentList 'tunnel','--config',`$tunnel,'--logfile',(Join-Path `$logs 'tunnel.log'),'--loglevel','warn','run','timer'
}
if (-not `$BackendOnly) {
    Start-Process -FilePath '$(Join-Path $client 'time_planner.exe')' -WorkingDirectory '$client'
}
"@ | Set-Content -LiteralPath $launcher -Encoding ascii

$shell = New-Object -ComObject WScript.Shell
$shortcut = $shell.CreateShortcut((Join-Path ([Environment]::GetFolderPath('Desktop')) 'Timer.lnk'))
$shortcut.TargetPath = (Get-Command powershell.exe).Source
$shortcut.Arguments = "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$launcher`""
$shortcut.WorkingDirectory = $home_
$shortcut.IconLocation = (Join-Path $client 'time_planner.exe') + ',0'
$shortcut.Description = 'Timer'
$shortcut.Save()
if (-not $LauncherOnly) { Write-Output "Installed client: $client" }
Write-Output "Launcher: $launcher"
Write-Output 'Desktop shortcut: Timer'
# robocopy reports success with exit codes 1-7; do not leak them as failure.
exit 0
